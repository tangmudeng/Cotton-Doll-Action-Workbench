const assert=require('node:assert/strict');
const workflow=require('../pixel-workflow.js');
const p={revision:4,builtRevision:4,artifact:{audit:{ok:true}},automation:{accepted:true,acceptedRevision:4,issues:[]}};
assert.equal(workflow(null).action,'reference');
assert.equal(workflow(p).action,'export');
assert.equal(workflow(p,{dirty:true}).export,false);
assert.equal(workflow(p,{dirty:true}).action,'auto');
assert.equal(workflow({...p,builtRevision:3}).export,false);
assert.equal(workflow({...p,automation:{...p.automation,acceptedRevision:3}}).export,false);
assert.equal(workflow(p,{job:{state:'running'}}).export,false);
assert.equal(workflow(p,{job:{state:'running'}}).action,null);
const candidate={...p,automation:{accepted:false,issues:[]}};
assert.equal(workflow(candidate).action,'inspect');
assert.equal(workflow(candidate,{reviewed:true}).action,'autoAccept');
assert.equal(workflow({...candidate,automation:{issues:[{code:'bend_flip'}]}},{reviewed:true}).autoAccept,false);
assert.equal(workflow({revision:1},{job:{state:'interrupted'}}).label,'重试 / 继续自动生成');
assert.equal(workflow(candidate).reviewExport,true);
assert.equal(workflow(candidate,{dirty:true}).reviewExport,false);
assert.equal(workflow(candidate,{job:{state:'failed'},reviewed:true}).autoAccept,false);
assert.equal(workflow(candidate,{job:{state:'failed'}}).action,'auto');
console.log('16 workflow state checks passed');
